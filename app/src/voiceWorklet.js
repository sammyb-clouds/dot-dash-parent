// AudioWorklet processor: forwards mic input to the main thread in 1024-sample
// Float32 chunks (at the context's rate). Loaded from a Blob URL by walkieCall.js.
class DotDashCapture extends AudioWorkletProcessor {
  constructor() {
    super();
    this.buf = new Float32Array(1024);
    this.n = 0;
  }
  process(inputs) {
    const ch = inputs[0] && inputs[0][0];
    if (ch) {
      for (let i = 0; i < ch.length; i++) {
        this.buf[this.n++] = ch[i];
        if (this.n === this.buf.length) {
          this.port.postMessage(this.buf.slice(0));
          this.n = 0;
        }
      }
    }
    return true;
  }
}
registerProcessor('dotdash-capture', DotDashCapture);
